# 5. MERGEWORKSPACE SOURCE MAP SEARCH
# ============================================================

Section "5. SOURCE MAP IDENTITY SEARCH"

$MapFiles = @(
    $Chunks |
    Where-Object {
        $_.Extension -eq ".map"
    }
)

Add-Line "Source maps: $($MapFiles.Count)"

foreach ($Map in $MapFiles) {

    $Text = SafeRead $Map.FullName

    if ($null -ne $Text) {

        $FoundComponent = TestPattern $Text "components/MergeWorkspace.tsx"
        $FoundPage = TestPattern $Text "app/merge-pdf/page.tsx"
        $FoundComponentName = TestPattern $Text "MergeWorkspace"

        if ($FoundComponent -or $FoundPage -or $FoundComponentName) {

            Add-Line ""
            Add-Line "RELEVANT MAP: $($Map.FullName)"
            Add-Line "  component path: $FoundComponent"
            Add-Line "  page path: $FoundPage"
            Add-Line "  component name: $FoundComponentName"
            Add-Line "  size: $($Map.Length)"
        }
    }
}

