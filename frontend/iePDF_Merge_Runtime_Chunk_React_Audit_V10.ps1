    $ServerFiles = @(
        Get-ChildItem `
            -LiteralPath $ServerRoot `
            -Recurse `
            -File `
            -ErrorAction SilentlyContinue |
        Where-Object {
            $_.Extension -eq ".js" -or
            $_.Extension -eq ".map"
        }
    )

    Add-Line "Server JS/map files: $($ServerFiles.Count)"

    foreach ($File in $ServerFiles) {

        $Text = SafeRead $File.FullName

        if ($null -ne $Text) {

            if (
                $Text.Contains("MergeWorkspace") -or
                $Text.Contains("application/x-iepdf-reorder") -or
                $Text.Contains("Add PDF Files") -or
                $Text.Contains("Select PDF Files")
            ) {

                Add-Line ""
                Add-Line "SERVER MATCH: $($File.FullName)"
                Add-Line "  MergeWorkspace: $(TestPattern $Text "MergeWorkspace")"
                Add-Line "  reorder marker: $(TestPattern $Text "application/x-iepdf-reorder")"
                Add-Line "  Add PDF Files: $(TestPattern $Text "Add PDF Files")"
                Add-Line "  Select PDF Files: $(TestPattern $Text "Select PDF Files")"
            }
        }
    }
}
else {
    Add-Line ".next/server not found"
