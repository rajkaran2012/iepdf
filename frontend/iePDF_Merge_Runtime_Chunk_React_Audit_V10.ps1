$Out = New-Object System.Collections.Generic.List[string]

function Add-Line {
    param([string]$Text = "")
    $Value = [string]$Text
    $Out.Add($Value)
    Write-Host $Value
}

function Section {
    param([string]$Title)

    Add-Line ""
    Add-Line ("=" * 80)
    Add-Line $Title
    Add-Line ("=" * 80)
}

function SafeRead {
    param([string]$Path)

    try {
        if (-not (Test-Path -LiteralPath $Path -PathType Leaf)) {
            return $null
        }

        return [System.IO.File]::ReadAllText($Path)
    }
    catch {
        return $null
    }
}

function TestPattern {
    param(
        [string]$Text,
        [string]$Pattern
    )

    if ($null -eq $Text) {
        return $false
    }

    return $Text.Contains($Pattern)
}

