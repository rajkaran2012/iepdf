# ============================================================
# 1. CURRENT SOURCE HASH / SIZE
# ============================================================

Section "1. CURRENT SOURCE IDENTITY"

$CurrentComponent = Join-Path $Root "components\MergeWorkspace.tsx"
$CurrentPage = Join-Path $Root "app\merge-pdf\page.tsx"

foreach ($Path in @($CurrentComponent, $CurrentPage)) {

    if (Test-Path -LiteralPath $Path) {

        $Info = Get-Item -LiteralPath $Path

        Add-Line ""
        Add-Line "FILE: $Path"
        Add-Line "SIZE: $($Info.Length)"
        Add-Line "LASTWRITE: $($Info.LastWriteTime)"

        try {
            $Hash = Get-FileHash -LiteralPath $Path -Algorithm SHA256
            Add-Line "SHA256: $($Hash.Hash)"
        }
        catch {
            Add-Line "SHA256: unavailable"
        }

    }
    else {

        Add-Line ""
        Add-Line "MISSING: $Path"
    }
}

# ============================================================
# 2. ALL .NEXT CHUNKS
# ============================================================

Section "2. GENERATED NEXT CHUNKS"

$NextStatic = Join-Path $Root ".next\static"

if (-not (Test-Path -LiteralPath $NextStatic)) {

    Add-Line "FAIL: .next/static does not exist"

}
else {

    $Chunks = @(
        Get-ChildItem `
            -LiteralPath $NextStatic `
            -Recurse `
            -File `
            -ErrorAction SilentlyContinue |
        Where-Object {
            $_.Extension -in @(".js",".map")
        }
    )

    Add-Line "Generated JS/map files: $($Chunks.Count)"

    $TotalBytes = 0

    foreach ($File in $Chunks) {
        $TotalBytes += $File.Length
    }

    Add-Line "Total generated bytes: $TotalBytes"
}

# ============================================================
# 3. SEARCH CURRENT COMPONENT SIGNATURE IN ALL CLIENT CHUNKS
# ============================================================

Section "3. CLIENT CHUNK SEARCH - CURRENT COMPONENT SIGNATURE"

$Patterns = @(
    "application/x-iepdf-reorder",
    "Add PDF Files",
    "Unlock & Merge",
    "Drag & drop PDFs here",
    "Processing happens in your browser",
    "files.map",
    "onReorderFiles",
    "onUnlockMerge",
    "onAddFiles"
)

foreach ($Pattern in $Patterns) {

    Add-Line ""
    Add-Line "PATTERN: $Pattern"

    $Matches = @()

    foreach ($File in $Chunks) {

        $Text = SafeRead $File.FullName

        if (TestPattern $Text $Pattern) {

            $Matches += $File
        }
    }

    if ($Matches.Count -eq 0) {

        Add-Line "  NOT FOUND"

    }
    else {

        Add-Line "  FOUND IN: $($Matches.Count) FILE(S)"

        foreach ($Match in $Matches) {

            Add-Line "  $($Match.FullName)"
            Add-Line "    SIZE: $($Match.Length)"
        }
    }
}

# ============================================================
# 4. SEARCH OLD UI SIGNATURE
# ============================================================

Section "4. CLIENT CHUNK SEARCH - OLD UI SIGNATURE"

$OldPatterns = @(
    "Select PDF Files",
    "showWorkspace",
    "setShowWorkspace",
    "workspaceFiles",
    "processSelectedFiles",
    "BrowserPdfAnalyzer"
)

foreach ($Pattern in $OldPatterns) {

